  if (!words.length) return [];
  const hits = addrIndex().filter(s => words.every(w => s.w.some(x => x.startsWith(w))))
    .sort((a, b) => (b.w.some(x => x === words[0]) - a.w.some(x => x === words[0])) || a.n.length - b.n.length).slice(0, 8);
